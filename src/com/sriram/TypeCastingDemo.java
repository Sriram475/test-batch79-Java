package com.sriram;

public class TypeCastingDemo {

	public static void main(String[] args) {
	  int num = 27727;
	  double d = num;
	  double d1 = 3778.6363;
	  int n = (int)d1;
	  int n1 = 'K';
	  char ch = 75;
	  System.out.println("int value is :" + num);
	  System.out.println("int to double is:" + d);
	  System.out.println("double to int is:" + n);
	  System.out.println("character to int is:" + n1);
	  System.out.println("int to character is:" + ch);
	  

	}

}
